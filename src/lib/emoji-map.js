export function resolveEmoji(client, emojiName) {
  const normalized = emojiName.toLowerCase().replace(/^:|:$/g, '');
  if (EMOJI_MAP[normalized]) return EMOJI_MAP[normalized];
  for (const guild of client.guilds.cache.values()) {
    const found = guild.emojis.cache.find(e => e.name?.toLowerCase() === normalized);
    if (found) return found;
  }
  return emojiName;
}
